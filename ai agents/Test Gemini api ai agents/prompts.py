def build_catalog_text(products):
    lines = []
    for p in products:
        status = f"متوفر ({p['stock']} قطعة)" if p["stock"] > 0 else "غير متوفر"
        lines.append(
            f"- رقم {p['id']}: {p['name']} | الفئة: {p['category']} | "
            f"السعر: {p['price']:.0f} جنيه | {status} | {p['description']}"
        )
    return "\n".join(lines)


